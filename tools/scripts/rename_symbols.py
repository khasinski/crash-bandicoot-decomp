#!/usr/bin/env python3
"""Symbol rename & audit utility for crash-pc (SCUS-949.00).

Safely renames functions, globals, and header references across:
  - configs/USA/sym.main.txt
  - configs/USA/main.yaml
  - src/ (C and assembly sources)
  - include/ (headers)
  - docs/ and tests/

Also provides an `--audit` mode that inspects the current naming state,
identifies `INCLUDE_ASM` vs C-decompiled symbols, checks inline `asm("...")`
symbol aliases, and flags known defects in `configs/USA/sym.main.txt`.

Usage:
    # Audit unnamed symbols, INCLUDE_ASM constraints, and known defects:
    python3 tools/scripts/rename_symbols.py --audit

    # Rename specific symbols (OLD NEW pairs):
    python3 tools/scripts/rename_symbols.py func_80011D88 Main_InitAndLoop
    python3 tools/scripts/rename_symbols.py --dry-run CORE_VSync VSync

    # Rename from a mapping file (one "OLD NEW" pair per line, # comments allowed):
    python3 tools/scripts/rename_symbols.py --map renames.txt
    python3 tools/scripts/rename_symbols.py --dry-run --map renames.txt

    # Bulk-replace a prefix across all symbols:
    python3 tools/scripts/rename_symbols.py --prefix CORE_ Main_
    python3 tools/scripts/rename_symbols.py --dry-run --prefix GOOL_ Gool_

    # Update #include directives after moving/renaming a header:
    python3 tools/scripts/rename_symbols.py --header old/path.h new/path.h
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

SEARCH_DIRS = ["src", "include", "configs", "docs", "tests"]
EXTENSIONS = {".c", ".h", ".s", ".S", ".txt", ".yaml", ".yml", ".md", ".inc"}

SYM_FILE = ROOT / "configs" / "USA" / "sym.main.txt"
YAML_FILE = ROOT / "configs" / "USA" / "main.yaml"

KNOWN_SYM_DEFECTS = [
    (
        "0x8001B3F0",
        "GOOL_TraverseObjectTreePreorder",
        "GOOL_InitLevelSpawns",
        "Off-by-one shift in sym.main.txt: 0x8001B3F0 is GOOL_InitLevelSpawns (src/main/gool/groups.c)",
    ),
    (
        "0x8001B648",
        "GOOL_TraverseObjectTreePostorder",
        "GOOL_TraverseObjectTreePreorder",
        "Off-by-one shift in sym.main.txt: 0x8001B648 is GOOL_TraverseObjectTreePreorder (src/main/engine/tree_visit_recursive.c)",
    ),
    (
        "0x8001B6F0",
        "(missing / func_8001B6F0)",
        "GOOL_TraverseObjectTreePostorder",
        "Unlisted in sym.main.txt due to shift: 0x8001B6F0 is GOOL_TraverseObjectTreePostorder (src/main/engine/tree_recursive.c)",
    ),
    (
        "0x8003E4F0",
        "CORE_VSync",
        "VSync",
        "Misattributed to game CORE_ namespace: 0x8003E4F0 is Sony PsyQ LIBETC.A:vsync.o VSync",
    ),
]


def iter_target_files(root: Path = ROOT, include_docs: bool = True) -> list[Path]:
    """Return sorted list of files eligible for symbol replacement."""
    files: list[Path] = []
    dirs = SEARCH_DIRS if include_docs else ["src", "include", "configs", "tests"]
    for d in dirs:
        base = root / d
        if not base.exists():
            continue
        for p in sorted(base.rglob("*")):
            if p.is_file() and p.suffix in EXTENSIONS:
                files.append(p)
    return files


def scan_include_asm_symbols(root: Path = ROOT) -> dict[str, list[Path]]:
    """Find all symbols referenced inside INCLUDE_ASM(...) macros.

    Note: Renaming an INCLUDE_ASM symbol requires the generated .s file under
    asm/USA/nonmatchings/.../<symbol>.s to match or be regenerated by splat.
    """
    inc_asm: dict[str, list[Path]] = {}
    pat = re.compile(r"INCLUDE_ASM\(\s*[^,]+\s*,\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)")
    src_dir = root / "src"
    if not src_dir.exists():
        return inc_asm
    for p in sorted(src_dir.rglob("*.c")):
        text = p.read_text(errors="replace")
        for m in pat.finditer(text):
            sym = m.group(1)
            inc_asm.setdefault(sym, []).append(p.relative_to(root))
    return inc_asm


def run_audit(root: Path = ROOT) -> int:
    """Inspect current symbol naming state across src/, include/, and configs/."""
    func_pat = re.compile(r"\bfunc_[0-9A-Fa-f]{8}\b")
    data_pat = re.compile(r"\bD_[0-9A-Fa-f]{8}\b")
    asm_label_pat = re.compile(r'__asm__\s*\(\s*"([A-Za-z_][A-Za-z0-9_]*)"\s*\)|asm\s*\(\s*"([A-Za-z_][A-Za-z0-9_]*)"\s*\)')

    c_func_defs: set[str] = set()
    c_func_refs: set[str] = set()
    data_refs: set[str] = set()
    asm_labels: set[str] = set()

    for p in sorted((root / "src").rglob("*.c")) + sorted((root / "include").rglob("*.h")):
        if not p.is_file():
            continue
        text = p.read_text(errors="replace")
        for m in func_pat.finditer(text):
            c_func_refs.add(m.group(0))
        for m in data_pat.finditer(text):
            data_refs.add(m.group(0))
        for m in asm_label_pat.finditer(text):
            lbl = m.group(1) or m.group(2)
            if lbl:
                asm_labels.add(lbl)
        if p.suffix == ".c":
            for m in re.finditer(r"\b(func_[0-9A-Fa-f]{8}|[A-Za-z_][A-Za-z0-9_]*)\s*\([^;{}]*?\)\s*\{", text):
                fn = m.group(1)
                if fn not in {"if", "while", "for", "switch"}:
                    c_func_defs.add(fn)

    inc_asm = scan_include_asm_symbols(root)
    unnamed_c_defs = sorted(fn for fn in c_func_defs if fn.startswith("func_"))
    named_c_defs = sorted(fn for fn in c_func_defs if not fn.startswith("func_"))

    sym_entries: dict[str, str] = {}
    if SYM_FILE.exists():
        for line in SYM_FILE.read_text(errors="replace").splitlines():
            m = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;", line)
            if m:
                sym_entries[m.group(2).upper()] = m.group(1)

    print("=== crash-pc Symbol Audit (SCUS-949.00) ===")
    print(f"Total entries in configs/USA/sym.main.txt : {len(sym_entries)}")
    print(f"Total C function definitions in src/      : {len(c_func_defs)}")
    print(f"  - Already named in C                    : {len(named_c_defs)}")
    print(f"  - Unnamed (func_800XXXXX) in C          : {len(unnamed_c_defs)}")
    print(f"Total INCLUDE_ASM functions in src/       : {len(inc_asm)}")
    print(f"Distinct func_800XXXXX tokens in src/inc  : {len(c_func_refs)}")
    print(f"Distinct D_800XXXXX tokens in src/inc     : {len(data_refs)}")
    print(f"Inline asm(\"...\") label bindings          : {len(asm_labels)}")
    print()

    print("=== Known Defects in configs/USA/sym.main.txt ===")
    for addr, cur_name, expected_name, note in KNOWN_SYM_DEFECTS:
        actual = sym_entries.get(addr.upper(), "(not in sym.main.txt)")
        status = "NEEDS FIX" if actual != expected_name else "FIXED"
        print(f"  [{status}] {addr}: current={actual!r} -> target={expected_name!r}")
        print(f"            {note}")
    print()

    docs_names = root / "docs" / "names.md"
    if docs_names.exists():
        print(f"Reference catalog available at: {docs_names.relative_to(root)}")

    return 0


def rename_symbols(
    renames: dict[str, str],
    dry_run: bool = False,
    allow_include_asm: bool = False,
    include_docs: bool = False,
    root: Path = ROOT,
) -> int:
    """Apply word-boundary symbol renames across target files."""
    if not renames:
        print("No renames specified.")
        return 0

    inc_asm = scan_include_asm_symbols(root)
    blocked = [old for old in renames if old in inc_asm]
    if blocked and not allow_include_asm:
        print(
            "WARNING: The following symbols are used inside INCLUDE_ASM(...) macros.\n"
            "Renaming them without re-running `make extract` (splat) will break the build\n"
            "because INCLUDE_ASM looks up `asm/USA/nonmatchings/<tu>/<symbol>.s` by filename.\n"
            "Pass `--allow-include-asm` if you also plan to update `configs/USA/sym.main.txt`\n"
            "and re-run `make extract`:",
            file=sys.stderr,
        )
        for sym in blocked:
            locs = ", ".join(str(p) for p in inc_asm[sym])
            print(f"  {sym} -> {renames[sym]} (in {locs})", file=sys.stderr)
        return 1

    escaped = sorted(renames.keys(), key=len, reverse=True)
    pattern = re.compile(r"\b(" + "|".join(re.escape(k) for k in escaped) + r")\b")

    files = iter_target_files(root, include_docs=include_docs)
    modified_files = 0
    total_replacements = 0

    for fpath in files:
        content = fpath.read_text(errors="replace")
        count = 0

        def replacer(match: re.Match[str]) -> str:
            nonlocal count
            count += 1
            return renames[match.group(0)]

        new_content = pattern.sub(replacer, content)
        if count > 0:
            modified_files += 1
            total_replacements += count
            rel = fpath.relative_to(root)
            prefix = "[DRY-RUN] " if dry_run else ""
            print(f"  {prefix}{rel}: {count} replacement(s)")
            if not dry_run:
                fpath.write_text(new_content)

    prefix = "[DRY-RUN] " if dry_run else ""
    print(f"\n{prefix}Summary: {total_replacements} replacement(s) across {modified_files} file(s).")
    return 0


def update_headers(old_header: str, new_header: str, dry_run: bool = False, root: Path = ROOT) -> int:
    """Update #include directives when a header file is renamed or moved."""
    pat = re.compile(
        r'(#\s*include\s*[<"])' + re.escape(old_header) + r'([>"])'
    )
    files = iter_target_files(root, include_docs=False)
    modified = 0
    for fpath in files:
        if fpath.suffix not in {".c", ".h", ".s", ".S", ".inc"}:
            continue
        content = fpath.read_text(errors="replace")
        new_content, count = pat.subn(rf"\g<1>{new_header}\g<2>", content)
        if count > 0:
            modified += 1
            rel = fpath.relative_to(root)
            prefix = "[DRY-RUN] " if dry_run else ""
            print(f"  {prefix}{rel}: {count} #include update(s)")
            if not dry_run:
                fpath.write_text(new_content)
    prefix = "[DRY-RUN] " if dry_run else ""
    print(f"\n{prefix}Updated #include in {modified} file(s).")
    return 0


def collect_prefix_renames(old_prefix: str, new_prefix: str, root: Path = ROOT) -> dict[str, str]:
    """Find all identifiers starting with old_prefix and map them to new_prefix."""
    pat = re.compile(r"\b(" + re.escape(old_prefix) + r"[A-Za-z0-9_]+)\b")
    renames: dict[str, str] = {}
    for fpath in iter_target_files(root, include_docs=False):
        content = fpath.read_text(errors="replace")
        for m in pat.finditer(content):
            sym = m.group(1)
            renames[sym] = new_prefix + sym[len(old_prefix) :]
    return renames


def load_map_file(map_path: Path) -> dict[str, str]:
    """Load OLD NEW pairs from a whitespace-separated mapping file."""
    renames: dict[str, str] = {}
    for lineno, raw in enumerate(map_path.read_text(errors="replace").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2:
            raise ValueError(f"{map_path}:{lineno}: expected 'OLD NEW', got: {raw!r}")
        old, new = parts
        if old != new:
            renames[old] = new
    return renames


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Rename symbols or audit naming conventions across the crash-pc codebase."
    )
    parser.add_argument(
        "pairs",
        nargs="*",
        help="Alternating OLD NEW symbol pairs to rename",
    )
    parser.add_argument(
        "--audit",
        action="store_true",
        help="Run a non-destructive audit of symbols and known sym.main.txt defects",
    )
    parser.add_argument(
        "--map",
        type=Path,
        help="File with OLD NEW symbol pairs (one per line, # comments allowed)",
    )
    parser.add_argument(
        "--prefix",
        nargs=2,
        metavar=("OLD_PREFIX", "NEW_PREFIX"),
        help="Replace identifier prefix (e.g. CORE_ Main_)",
    )
    parser.add_argument(
        "--header",
        nargs=2,
        metavar=("OLD_HEADER", "NEW_HEADER"),
        help="Update #include directives from OLD_HEADER to NEW_HEADER",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview changes without modifying any files",
    )
    parser.add_argument(
        "--allow-include-asm",
        action="store_true",
        help="Allow renaming symbols referenced in INCLUDE_ASM(...) macros",
    )
    parser.add_argument(
        "--include-docs",
        action="store_true",
        help="Also replace occurrences inside docs/ markdown files",
    )
    args = parser.parse_args()

    if args.audit:
        return run_audit(ROOT)

    if args.header:
        return update_headers(args.header[0], args.header[1], dry_run=args.dry_run, root=ROOT)

    renames: dict[str, str] = {}

    if args.map:
        renames.update(load_map_file(args.map))

    if args.prefix:
        old_p, new_p = args.prefix
        prefix_map = collect_prefix_renames(old_p, new_p, root=ROOT)
        print(f"Found {len(prefix_map)} symbol(s) with prefix '{old_p}'")
        renames.update(prefix_map)

    if args.pairs:
        if len(args.pairs) % 2 != 0:
            parser.error("Positional arguments must be alternating OLD NEW pairs.")
        for i in range(0, len(args.pairs), 2):
            old, new = args.pairs[i], args.pairs[i + 1]
            if old != new:
                renames[old] = new

    if not renames:
        parser.print_help()
        return 0

    return rename_symbols(
        renames,
        dry_run=args.dry_run,
        allow_include_asm=args.allow_include_asm,
        include_docs=args.include_docs,
        root=ROOT,
    )


if __name__ == "__main__":
    sys.exit(main())
